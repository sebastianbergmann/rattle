namespace SebastianBergmann\Rattle\Instrumentation;

use function array_keys;
use function array_pop;
use function end;
use function in_array;
use function spl_object_id;
use function str_contains;
use function strlen;
use function strtolower;
use PhpParser\Node;
use PhpParser\Node\Expr;
use PhpParser\Node\Name;
use PhpParser\Node\Scalar;
use PhpParser\Node\Stmt;
use PhpParser\NodeVisitorAbstract;

/**
 * Finds the constant operands of the comparisons in a file, which are tokens
 * for the dictionary: values that the code compares the data it works on
 * with, which are unlikely to be generated byte by byte.
 *
 * The comparisons are:
 *
 * - ===, !==, ==, !=, <, <=, >, >=, and <=>
 * - the conditions of the arms of a match and the values of the cases of a
 *   switch
 * - calls of functions that compare strings or look for them, such as
 *   str_starts_with(), strcmp(), in_array(), and explode()
 *
 * A constant operand is a string, an integer, an array whose keys and values
 * are, or a class constant whose value is one of these. A class constant is
 * only resolved when it is declared in the same file and fetched through
 * self, static, or the name of its class, of which only the last part is
 * compared.
 *
 * An integer becomes its decimal representation. Operands that are shorter
 * than three bytes are left out: they are generated easily, and inserting
 * them gets in the way more often than it helps. Operands that are longer
 * than 64 bytes are left out, too.
 *
 * @no-named-arguments Parameter names are not covered by the backward compatibility promise for sebastian/rattle
 *
 * @internal This class is not covered by the backward compatibility promise for sebastian/rattle
 */
final class ComparisonOperandFinder extends NodeVisitorAbstract
{
    private const int SHORTEST_TOKEN = 3;
    private const int LONGEST_TOKEN  = 64;

    /**
     * The functions that compare strings or look for them, in lowercase.
     */
    private const array FUNCTIONS = [
        'array_key_exists',
        'array_search',
        'explode',
        'hash_equals',
        'in_array',
        'key_exists',
        'mb_stripos',
        'mb_stristr',
        'mb_strpos',
        'mb_strripos',
        'mb_strrpos',
        'mb_strstr',
        'str_contains',
        'str_ends_with',
        'str_starts_with',
        'strcasecmp',
        'strcmp',
        'stripos',
        'stristr',
        'strnatcasecmp',
        'strnatcmp',
        'strncasecmp',
        'strncmp',
        'strpos',
        'strrchr',
        'strripos',
        'strrpos',
        'strstr',
        'substr_compare',
        'substr_count',
    ];

    /**
     * @var array<non-empty-string, true>
     */
    private array $operands = [];

    /**
     * The class-likes that enclose the current node, by their object IDs.
     *
     * @var list<int>
     */
    private array $classes = [];

    /**
     * The object IDs of the named class-likes of the file, by their names in
     * lowercase.
     *
     * @var array<string, int>
     */
    private array $classesByName = [];

    /**
     * The values of the constants of the class-likes of the file, by the
     * object IDs of the class-likes and the names of the constants.
     *
     * @var array<int, array<string, Expr>>
     */
    private array $constants = [];

    /**
     * The class constants that are operands, resolved after the whole file
     * was traversed, because a constant can be declared after it is used.
     *
     * @var list<array{class: int, constant: string}>
     */
    private array $constantOperands = [];

    /**
     * @return list<non-empty-string>
     */
    public function operands(): array
    {
        $operands = [];

        // a key that is the decimal representation of an integer became an
        // integer, which turns back into the same string
        foreach (array_keys($this->operands) as $operand) {
            $operands[] = (string) $operand;
        }

        return $operands;
    }

    public function enterNode(Node $node): null
    {
        if ($node instanceof Stmt\ClassLike) {
            $this->classes[] = spl_object_id($node);

            if ($node->name !== null) {
                $this->classesByName[$node->name->toLowerString()] = spl_object_id($node);
            }

            return null;
        }

        if ($node instanceof Stmt\ClassConst && $this->classes !== []) {
            foreach ($node->consts as $constant) {
                $this->constants[end($this->classes)][$constant->name->toString()] = $constant->value;
            }

            return null;
        }

        if ($node instanceof Expr\BinaryOp\Identical ||
            $node instanceof Expr\BinaryOp\NotIdentical ||
            $node instanceof Expr\BinaryOp\Equal ||
            $node instanceof Expr\BinaryOp\NotEqual ||
            $node instanceof Expr\BinaryOp\Smaller ||
            $node instanceof Expr\BinaryOp\SmallerOrEqual ||
            $node instanceof Expr\BinaryOp\Greater ||
            $node instanceof Expr\BinaryOp\GreaterOrEqual ||
            $node instanceof Expr\BinaryOp\Spaceship) {
            $this->operand($node->left);
            $this->operand($node->right);

            return null;
        }

        if ($node instanceof Node\MatchArm && $node->conds !== null) {
            foreach ($node->conds as $condition) {
                $this->operand($condition);
            }

            return null;
        }

        if ($node instanceof Stmt\Case_ && $node->cond !== null) {
            $this->operand($node->cond);

            return null;
        }

        if ($node instanceof Expr\FuncCall && $this->comparesStrings($node->name)) {
            foreach ($node->getRawArgs() as $argument) {
                if ($argument instanceof Node\Arg) {
                    $this->operand($argument->value);
                }
            }
        }

        return null;
    }

    public function leaveNode(Node $node): null
    {
        if ($node instanceof Stmt\ClassLike) {
            array_pop($this->classes);
        }

        return null;
    }

    public function afterTraverse(array $nodes): null
    {
        foreach ($this->constantOperands as $operand) {
            $value = $this->constants[$operand['class']][$operand['constant']] ?? null;

            if ($value !== null) {
                $this->literal($value);
            }
        }

        return null;
    }

    private function operand(Expr $expression): void
    {
        if ($expression instanceof Expr\ClassConstFetch &&
            $expression->class instanceof Name &&
            $expression->name instanceof Node\Identifier) {
            $class = $this->classOf($expression->class);

            if ($class !== null) {
                $this->constantOperands[] = ['class' => $class, 'constant' => $expression->name->toString()];
            }

            return;
        }

        $this->literal($expression);
    }

    private function literal(Expr $expression): void
    {
        if ($expression instanceof Scalar\String_) {
            $this->add($expression->value);

            return;
        }

        if ($expression instanceof Scalar\Int_) {
            $this->add((string) $expression->value);

            return;
        }

        if ($expression instanceof Expr\UnaryMinus && $expression->expr instanceof Scalar\Int_) {
            $this->add('-' . $expression->expr->value);

            return;
        }

        if ($expression instanceof Expr\Array_) {
            foreach ($expression->items as $item) {
                if ($item->key !== null) {
                    $this->literal($item->key);
                }

                $this->literal($item->value);
            }
        }
    }

    private function add(string $operand): void
    {
        if (strlen($operand) >= self::SHORTEST_TOKEN && strlen($operand) <= self::LONGEST_TOKEN) {
            $this->operands[$operand] = true;
        }
    }

    /**
     * The object ID of the class-like that a name in a class constant fetch
     * refers to, or null when it is not declared in the file.
     */
    private function classOf(Name $name): ?int
    {
        $lowercase = $name->toLowerString();

        if ($lowercase === 'self' || $lowercase === 'static') {
            return $this->classes === [] ? null : end($this->classes);
        }

        return $this->classesByName[strtolower($name->getLast())] ?? null;
    }

    /**
     * Whether a function is called that compares strings or looks for them,
     * by an unqualified name or by a fully qualified name in the global
     * namespace. An unqualified name in a namespace refers to the global
     * function unless the namespace declares a function of that name, which
     * is unlikely for these names.
     */
    private function comparesStrings(Expr|Name $name): bool
    {
        if (!$name instanceof Name || $name->isRelative() || str_contains($name->toString(), '\\')) {
            return false;
        }

        return in_array($name->toLowerString(), self::FUNCTIONS, true);
    }
}
